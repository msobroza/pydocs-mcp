"""Install, and lock, the third-party dependency set of a bench VM image.

Two subcommands, both stdlib-only, so the builder stage runs them on the bare
uv-managed interpreter before anything else is installed:

``install --flavour cpu|cuda --repo DIR``
    Installs every third-party dependency of one image flavour into the active
    virtual environment, with hashes checked and nothing resolved:

    * the product's set comes from ``uv.lock`` itself (``uv export --frozen``),
      with the flavour's extras (``FLAVOUR_EXTRAS``);
    * the eval suite's set comes from ``eval-requirements.txt`` — the eval
      suite is not in ``uv.lock`` (it is not a workspace member), so that file
      is its lock, compiled against ``uv.lock`` by ``lock-eval``. Packages the
      product set already pins are dropped from it, so each package is
      installed once, at the ``uv.lock`` version;
    * the CUDA flavour swaps the CPU ONNX runtimes for the pinned GPU builds in
      ``cuda-swaps.txt``.

``check --flavour cpu|cuda``
    ``uv pip check`` over the finished environment. The only gaps it accepts
    are the CUDA swaps: the product requires ``fastembed`` and the CUDA image
    satisfies that with ``fastembed-gpu``, which ships the same module.

``nvidia-ld-conf --output FILE``
    Writes torch's ``nvidia/*/lib`` dirs for ``ldconfig``: the CUDA image's
    baked-in form of the library-path fix ``run_eval_gpu.sh`` applies.

``lock-eval --repo DIR [--check]``
    Regenerates ``eval-requirements.txt`` (needs network), resolving only what
    PyPI held at a cutoff of now, which the file's header records. Run it
    whenever ``benchmarks/pyproject.toml`` or ``uv.lock`` changes; ``--check``
    recompiles at the recorded cutoff and exits non-zero when the committed
    file is stale, so a release published after the cutoff never fails it.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import subprocess
import sys
import tempfile
import tomllib
from collections.abc import Iterable, Sequence
from enum import StrEnum
from pathlib import Path


class ImageFlavour(StrEnum):
    CPU = "cpu"
    CUDA = "cuda"


# WHY: the CPU image carries no CUDA library. On Linux, uv.lock resolves torch
# as a CUDA 13 build with its nvidia-* wheels, and torch arrives only through
# the torch-backed extras, so the CPU flavour leaves them to the CUDA flavour.
# [graph] (networkx + scipy) is torch-free and serves the graph-rerank configs.
FLAVOUR_EXTRAS: dict[ImageFlavour, tuple[str, ...]] = {
    ImageFlavour.CPU: ("graph",),
    ImageFlavour.CUDA: ("graph", "sentence-transformers", "late-interaction"),
}

# The CUDA flavour replaces these locked CPU distributions with the GPU builds
# pinned in cuda-swaps.txt; each pair ships the same import package.
CUDA_SWAPS: dict[str, str] = {
    "fastembed": "fastembed-gpu",
    "onnxruntime": "onnxruntime-gpu",
}

RECIPE_DIR = Path(__file__).resolve().parent
EVAL_LOCK_FILE = RECIPE_DIR / "eval-requirements.txt"
CUDA_SWAPS_FILE = RECIPE_DIR / "cuda-swaps.txt"
BUILD_CONSTRAINTS_FILE = RECIPE_DIR / "build-constraints.txt"

# Every image runs one interpreter on one platform; the eval lock is compiled
# for exactly that target.
LOCK_PYTHON_VERSION = "3.11"
LOCK_PYTHON_PLATFORM = "x86_64-manylinux_2_28"
_PRODUCT_NAME = "pydocs-mcp"
_EVAL_EXTRA = "all"

_REQUIREMENT_START = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)\s*(==|@)")
_EVAL_LOCK_HEADER = (
    "# The eval suite's third-party dependency set for the bench VM images.\n"
    "# GENERATED by `python infra/bench-vm/docker/image_deps.py lock-eval "
    "--repo .`\n"
    "# from benchmarks/pyproject.toml (base + [all], minus pydocs-mcp), compiled "
    "against\n"
    "# uv.lock's export so every shared package keeps its uv.lock version. "
    "Do not edit.\n"
)
# WHY a recorded cutoff: the eval-only packages (mlflow's closure, gepa, ...)
# are pinned by nothing in uv.lock, so an unbounded re-resolve follows every
# PyPI release — 2 of the 52 drifted within 30 hours of the first lock — and a
# freshness check would fail on changes that touched no input. Resolving only
# what was uploaded before the cutoff (uv's --exclude-newer) lets `--check`
# reproduce the committed file until uv.lock or benchmarks/pyproject.toml
# change; regenerating moves the cutoff to now.
_EXCLUDE_NEWER_PREFIX = "# exclude-newer: "
_RERUN_LOCK_EVAL = "re-run `image_deps.py lock-eval --repo .`"


def normalize_name(name: str) -> str:
    """PEP 503 normalized distribution name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def split_requirement_blocks(text: str) -> dict[str, str]:
    """Map each pinned requirement's normalized name to its full block.

    A block is the ``name==version [; marker] \\`` line plus its indented
    ``--hash`` continuation lines, as ``uv export`` and ``uv pip compile``
    write them. Comments and blank lines are dropped.
    """
    blocks: dict[str, list[str]] = {}
    current: list[str] | None = None
    for line in text.splitlines():
        match = _REQUIREMENT_START.match(line)
        if match:
            current = blocks.setdefault(normalize_name(match.group(1)), [])
            current.append(line)
        elif current is not None and line.startswith((" ", "\t")):
            current.append(line)
        else:
            current = None
    return {name: "\n".join(lines) for name, lines in blocks.items()}


def pinned_version(block: str) -> str:
    """The ``==`` version of one requirement block, or ``""`` for a URL pin."""
    match = re.match(r"^[^=@\s]+\s*==\s*([^\s;\\]+)", block)
    return match.group(1) if match else ""


def without_names(blocks: dict[str, str], names: Iterable[str]) -> dict[str, str]:
    drop = {normalize_name(name) for name in names}
    return {name: block for name, block in blocks.items() if name not in drop}


def render_requirements(blocks: dict[str, str]) -> str:
    return "".join(block + "\n" for _, block in sorted(blocks.items()))


def eval_requirements(benchmarks_pyproject: Path) -> list[str]:
    """The eval suite's base + ``[all]`` requirements, minus the product."""
    project = tomllib.loads(benchmarks_pyproject.read_text())["project"]
    requirements = project["dependencies"] + project["optional-dependencies"][_EVAL_EXTRA]
    return [r for r in requirements if not re.match(rf"{_PRODUCT_NAME}\b", r)]


def unexpected_check_failures(report: str, flavour: ImageFlavour) -> list[str]:
    """The ``uv pip check`` lines the flavour does not explain.

    The CUDA flavour leaves the product's ``fastembed`` requirement to
    ``fastembed-gpu`` (same module), so that one gap is expected there.
    """
    allowed = set(CUDA_SWAPS) if flavour is ImageFlavour.CUDA else set()
    failures = []
    for line in report.splitlines():
        missing = re.search(r"requires `([A-Za-z0-9._-]+)", line)
        if missing and normalize_name(missing.group(1)) in allowed:
            continue
        if re.search(r"requires|incompatible|not installed|missing", line):
            failures.append(line.strip())
    return failures


def nvidia_library_dirs() -> list[str]:
    """The ``nvidia/*/lib`` dirs of torch's locked NVIDIA wheels, sorted.

    The same glob ``benchmarks/scripts/run_eval_gpu.sh`` prepends to
    ``LD_LIBRARY_PATH`` at run time: onnxruntime's CUDA provider finds
    libcublasLt / libcudnn only through the dynamic linker's search path,
    while torch finds them through its own RPATH. The CUDA image bakes these
    dirs into the linker cache instead, so no wrapper is needed.
    """
    try:
        import nvidia  # type: ignore[import-not-found]
    except ImportError:
        return []
    return sorted({str(lib) for root in nvidia.__path__ for lib in Path(root).glob("*/lib")})


def write_nvidia_ld_conf(output: Path) -> None:
    dirs = nvidia_library_dirs()
    if not dirs:
        raise SystemExit("no nvidia/*/lib dirs found: torch's NVIDIA wheels are not installed")
    output.write_text("".join(f"{d}\n" for d in dirs))
    print(f"wrote {len(dirs)} NVIDIA library dirs to {output}", flush=True)


def _run(argv: Sequence[str], *, capture: bool = False) -> str:
    print("+ " + " ".join(argv), flush=True)
    completed = subprocess.run(argv, check=False, text=True, capture_output=capture)  # noqa: S603 — argv is built here from constants and parsed args
    if completed.returncode != 0:
        detail = (completed.stdout + completed.stderr) if capture else ""
        raise SystemExit(f"command failed ({completed.returncode}): {' '.join(argv)}\n{detail}")
    return completed.stdout if capture else ""


def export_locked_set(repo: Path, selection: Sequence[str]) -> str:
    """A third-party set straight from uv.lock, hashes included.

    ``selection`` holds the ``uv export`` flags choosing extras and groups.
    """
    argv = ["uv", "export", "--frozen", "--no-emit-project", *selection]
    argv += ["--format=requirements-txt", "--no-header", f"--project={repo}"]
    return _run(argv, capture=True)


def export_locked_product_set(repo: Path, extras: Sequence[str]) -> str:
    """One flavour's product set: the runtime deps plus ``extras``, no dev groups."""
    return export_locked_set(repo, ["--no-default-groups", *(f"--extra={e}" for e in extras)])


def install(repo: Path, flavour: ImageFlavour) -> None:
    product = split_requirement_blocks(export_locked_product_set(repo, FLAVOUR_EXTRAS[flavour]))
    eval_only = without_names(split_requirement_blocks(EVAL_LOCK_FILE.read_text()), product)
    files = {"product.txt": product, "eval.txt": eval_only}
    if flavour is ImageFlavour.CUDA:
        files["product.txt"] = without_names(product, CUDA_SWAPS)
        files["cuda-swaps.txt"] = split_requirement_blocks(CUDA_SWAPS_FILE.read_text())
    with tempfile.TemporaryDirectory() as scratch:
        # --no-config: the repo's [tool.uv] constraint-dependencies are ranges,
        # which --require-hashes refuses; uv.lock already honours them.
        argv = [
            "uv",
            "pip",
            "install",
            "--no-config",
            "--require-hashes",
            "--no-deps",
            "--no-build",
        ]
        for filename, blocks in files.items():
            path = Path(scratch) / filename
            path.write_text(render_requirements(blocks))
            argv += ["--requirement", str(path)]
        _run(argv)


def check(flavour: ImageFlavour) -> None:
    # uv is on PATH in the builder stage (and wherever this is run by hand).
    completed = subprocess.run(
        ["uv", "pip", "check"],  # noqa: S607
        check=False,
        text=True,
        capture_output=True,
    )
    failures = unexpected_check_failures(completed.stdout + completed.stderr, flavour)
    if failures:
        raise SystemExit("uv pip check found unexplained gaps:\n" + "\n".join(failures))
    print(f"uv pip check: clean for the {flavour} flavour", flush=True)


def compile_eval_lock(repo: Path, *, exclude_newer: str) -> str:
    """Compile the eval lock against everything uv.lock pins, as of ``exclude_newer``.

    WHY all extras and groups, not just the image flavours': a package the
    eval suite shares with ANY part of uv.lock (gitpython via the ask harness,
    say) then keeps its uv.lock version, and with it the security floors of
    the root pyproject's [tool.uv] constraint-dependencies.
    """
    product = split_requirement_blocks(export_locked_set(repo, ["--all-extras", "--all-groups"]))
    with tempfile.TemporaryDirectory() as scratch:
        requirements = Path(scratch) / "eval.in"
        requirements.write_text("\n".join(eval_requirements(repo / "benchmarks/pyproject.toml")))
        constraints = Path(scratch) / "constraints.txt"
        constraints.write_text(render_requirements(product))
        argv = ["uv", "pip", "compile", str(requirements), "--constraint", str(constraints)]
        argv += [f"--python-version={LOCK_PYTHON_VERSION}"]
        argv += [f"--python-platform={LOCK_PYTHON_PLATFORM}"]
        argv += [f"--exclude-newer={exclude_newer}"]
        argv += ["--generate-hashes", "--no-header", "--no-annotate", "--quiet"]
        compiled = split_requirement_blocks(_run(argv, capture=True))
    cutoff_line = f"{_EXCLUDE_NEWER_PREFIX}{exclude_newer}\n"
    return _EVAL_LOCK_HEADER + cutoff_line + render_requirements(compiled)


def recorded_exclude_newer(lock_text: str) -> str | None:
    """The cutoff a generated eval lock was resolved at, read from its header."""
    for line in lock_text.splitlines():
        if not line.startswith("#"):
            return None
        if line.startswith(_EXCLUDE_NEWER_PREFIX):
            return line.removeprefix(_EXCLUDE_NEWER_PREFIX).strip()
    return None


def current_cutoff() -> str:
    """Now, to the second, as the RFC 3339 timestamp uv's --exclude-newer takes."""
    now = dt.datetime.now(dt.UTC).replace(microsecond=0)
    return now.isoformat().replace("+00:00", "Z")


def check_eval_lock(repo: Path) -> None:
    committed = EVAL_LOCK_FILE.read_text()
    cutoff = recorded_exclude_newer(committed)
    if cutoff is None:
        prefix = _EXCLUDE_NEWER_PREFIX.strip()
        raise SystemExit(f"{EVAL_LOCK_FILE} records no `{prefix}` cutoff: {_RERUN_LOCK_EVAL}")
    try:
        fresh = compile_eval_lock(repo, exclude_newer=cutoff)
    except SystemExit as failed:
        # A uv.lock pin newer than the cutoff cannot resolve at it: an input moved.
        raise SystemExit(
            f"{EVAL_LOCK_FILE} does not resolve at its cutoff {cutoff}: {_RERUN_LOCK_EVAL}\n{failed}"
        ) from None
    if committed != fresh:
        raise SystemExit(f"{EVAL_LOCK_FILE} is stale: {_RERUN_LOCK_EVAL}")
    print(f"{EVAL_LOCK_FILE.name} is current (exclude-newer {cutoff})", flush=True)


def lock_eval(repo: Path, *, check_only: bool) -> None:
    if check_only:
        check_eval_lock(repo)
        return
    cutoff = current_cutoff()
    EVAL_LOCK_FILE.write_text(compile_eval_lock(repo, exclude_newer=cutoff))
    print(f"wrote {EVAL_LOCK_FILE} (exclude-newer {cutoff})", flush=True)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    flavours = [flavour.value for flavour in ImageFlavour]
    install_cmd = commands.add_parser("install", help="install one flavour's locked set")
    install_cmd.add_argument("--flavour", required=True, choices=flavours)
    install_cmd.add_argument("--repo", required=True, type=Path)
    check_cmd = commands.add_parser("check", help="uv pip check, flavour-aware")
    check_cmd.add_argument("--flavour", required=True, choices=flavours)
    lock_cmd = commands.add_parser("lock-eval", help="regenerate eval-requirements.txt")
    lock_cmd.add_argument("--repo", required=True, type=Path)
    lock_cmd.add_argument("--check", action="store_true", help="fail when the file is stale")
    conf_cmd = commands.add_parser(
        "nvidia-ld-conf", help="write the NVIDIA wheel dirs for ldconfig"
    )
    conf_cmd.add_argument("--output", required=True, type=Path)
    return parser


def main(argv: Sequence[str] | None = None) -> None:
    args = _parser().parse_args(argv)
    if args.command == "install":
        install(args.repo.resolve(), ImageFlavour(args.flavour))
    elif args.command == "check":
        check(ImageFlavour(args.flavour))
    elif args.command == "nvidia-ld-conf":
        write_nvidia_ld_conf(args.output)
    else:
        lock_eval(args.repo.resolve(), check_only=args.check)


if __name__ == "__main__":
    sys.exit(main())
